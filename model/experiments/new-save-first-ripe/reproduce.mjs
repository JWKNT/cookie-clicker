import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { loadGameSource, SOURCE_HASHES } from './snapshot/model/game-source.mjs';
import { completionPolicySource } from './snapshot/model/completion-policy.mjs';

const root=dirname(fileURLToPath(import.meta.url));
const read=name=>JSON.parse(readFileSync(join(root,name),'utf8'));
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const args=process.argv.slice(2), value=key=>{const i=args.indexOf(key);return i<0?null:args[i+1];};
if(args.includes('--check')===args.includes('--run'))throw new Error('Choose --check or --run OUTPUT_DIR; also supply --source GAME_SRC_DIR.');
const sourceDirectory=value('--source')||process.env.COOKIE_CLICKER_SOURCE;
if(!sourceDirectory)throw new Error('Supply --source GAME_SRC_DIR or COOKIE_CLICKER_SOURCE. Only game source files are read; no save is read.');
const manifest=read('manifest.json');
for(const [path,expected] of Object.entries(manifest.payloadSha256))assert.equal(sha(readFileSync(join(root,path))),expected,`Archive hash: ${path}`);
const policy=readFileSync(join(root,manifest.policy.file));
assert.equal(policy.at(-1),10,'The archived policy must retain its original appended LF');
assert.equal(sha(policy),manifest.policy.fileSha256);
assert.equal(sha(policy.subarray(0,-1)),manifest.policy.evaluatedSha256);
const start=read('original-start.json'), generated=completionPolicySource(start.config);
assert.equal(sha(generated),manifest.policy.evaluatedSha256,'Frozen policy generator');
assert.equal(policy.toString('utf8'),generated+'\n');
const source=loadGameSource(resolve(sourceDirectory));
assert.deepEqual(source.hashes,SOURCE_HASHES);
const observed=read('public-progress.json');
assert.deepEqual(observed.summary,manifest.observedCheckpoint);
assert.equal(observed.summary.firstCompletionMs,null);
assert.equal(observed.summary.temple.level,1);
const prefixLines=readFileSync(join(root,'log-prefix.log'),'utf8').trim().split('\n').map(line=>JSON.parse(line));
const recorded=prefixLines.find(line=>line.elapsedMs===observed.summary.elapsedMs&&line.decisions===observed.summary.decisions);
assert.ok(recorded,'The public checkpoint must occur in the original log prefix');
for(const [key,value] of Object.entries(observed.summary))assert.deepEqual(recorded[key],value,`Log field ${key}`);
const original=readFileSync(join(root,'original-runner.mjs'),'utf8');
const insertion="\n   // Diagnostic stop only: preserve the original horizon and all earlier actions.\n   if(o.elapsedMs>=95400678){status='censored-prefix';break;}";
assert.equal(readFileSync(join(root,'snapshot/tools/run-first-ripe.mjs'),'utf8'),original.replace('   nextProgress=o.elapsedMs+1800000;','   nextProgress=o.elapsedMs+1800000;'+insertion));
const runtime={node:process.version,v8:process.versions.v8,platform:process.platform,architecture:process.arch};
const runtimeMatches=JSON.stringify(runtime)===JSON.stringify(manifest.externalDependencies.node);
const check={archiveIntegrity:true,frozenPolicyRegenerated:true,sourceHashes:source.hashes,runtime,runtimeMatches,observedElapsedMs:observed.summary.elapsedMs,fullReplay:false,expectedTimeCertified:false,optimalityCertified:false};
if(args.includes('--check')){console.log(JSON.stringify(check,null,2));process.exit(0);}
assert.ok(runtimeMatches,'Use the recorded Node/V8/platform/architecture for a claimed reproduction');
const outputArgument=value('--run');if(!outputArgument||outputArgument.startsWith('--'))throw new Error('--run requires a new output directory');
const output=resolve(outputArgument);if(existsSync(output)&&readdirSync(output).length)throw new Error('The output directory must be absent or empty');
mkdirSync(output,{recursive:true});
for(const path of Object.keys(manifest.payloadSha256).filter(path=>path.startsWith('snapshot/'))){const target=join(output,path.slice('snapshot/'.length));mkdirSync(dirname(target),{recursive:true});copyFileSync(join(root,path),target);}
writeFileSync(join(output,'reproduction-input-check.json'),JSON.stringify(check,null,2)+'\n');
const result=spawnSync(process.execPath,['tools/run-first-ripe.mjs',String(start.horizon),'full-route'],{cwd:output,env:{...process.env,COOKIE_CLICKER_SOURCE:resolve(sourceDirectory)},stdio:'inherit'});
if(result.error)throw result.error;if(result.status!==0)process.exit(result.status||1);
const actual=JSON.parse(readFileSync(join(output,'full-route-public-progress.json'),'utf8'));
assert.deepEqual(actual.observation,observed.observation,'Reproduced public game observation');
assert.deepEqual(actual.memory,observed.memory,'Reproduced controller memory');
for(const key of Object.keys(observed.summary).filter(key=>!['wallSeconds','rss'].includes(key)))assert.deepEqual(actual.summary[key],observed.summary[key],`Reproduced summary ${key}`);
console.log(JSON.stringify({reproducedObservedPrefix:true,elapsedMs:actual.summary.elapsedMs,scope:manifest.scope},null,2));
