#!/usr/bin/env python3
"""Generate Lean identities from the exact full-game completion requirements."""

import argparse
import hashlib
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parent
repository = root.parent
requirements_path = repository / "model/completion-requirements.json"
catalogue_path = repository / "model/catalogue.json"
requirements_bytes = requirements_path.read_bytes()
r = json.loads(requirements_bytes)
c = json.loads(catalogue_path.read_bytes())
quote = lambda value: json.dumps(value, ensure_ascii=False)

lines = [
    "import CookieClicker.FullCompletion", "",
    "/-! Generated by lean/generate_inventory.py from model/completion-requirements.json.",
    "Identity extraction and game transitions are not proved by these constants. -/",
    "namespace CookieClicker.FullGame.Pinned", "",
    f'def requirementsSha256 : String := {quote(hashlib.sha256(requirements_bytes).hexdigest())}',
    f'def profileId : String := {quote(r["profileId"])}',
    f'def profileVersion : String := {quote(r["profileVersion"])}',
]

def emit_list(name, lean_type, items, render):
    lines.extend(["", f"def {name} : List {lean_type} := ["])
    lines.extend("  " + render(item) + ("," if index + 1 < len(items) else "")
                 for index, item in enumerate(items))
    lines.append("]")

emit_list("sourceHashes", "(String × String)", list(r["sourceHashes"].items()),
          lambda item: f"({quote(item[0])}, {quote(item[1])})")
for name, field, identity_field in [
    ("achievementIdentities", "requiredAchievements", "name"),
    ("normalAchievementIdentities", "normalAchievements", "name"),
    ("ownedUpgradeIdentities", "ownedUpgrades", "name"),
    ("accessUpgradeIdentities", "accessUpgrades", "name"),
    ("seedIdentities", "seeds", "key"),
    ("spellIdentities", "spells", "key"),
    ("godIdentities", "gods", "key"),
    ("sugarExclusions", "excludedAchievements", "name"),
]:
    emit_list(name, "(Nat × String)", r[field], lambda item, key=identity_field:
              f'({item["id"]}, {quote(item[key])})')
emit_list("shadowExclusions", "(Nat × String)", [item for item in c["achievements"] if item["pool"] == "shadow"],
          lambda item: f'({item["id"]}, {quote(item["name"])})')
lines.extend(["", "def requirements : Requirements where",
    f'  gameVersion := {quote(r["gameVersion"])}', f'  edition := {quote(r["edition"])}',
    "  achievements := achievementIdentities.map Prod.snd",
    "  normalAchievements := normalAchievementIdentities.map Prod.snd",
    f'  minimumNormalAchievements := {r["minimumNormalAchievements"]}',
    "  ownedUpgrades := ownedUpgradeIdentities.map Prod.snd",
    "  accessUpgrades := accessUpgradeIdentities.map Prod.snd",
    "  seeds := seedIdentities.map Prod.snd",
    "  soils := [" + ", ".join(f'({quote(item["key"])}, {item["farmAmount"]})' for item in r["soils"]) + "]",
    "  minigames := [" + ", ".join(quote(item["building"]) for item in r["minigames"]) + "]",
    "  buildingLevels := [" + ", ".join(f'({quote(item["building"])}, {item["level"]})' for item in r["buildingLevels"]) + "]",
    "  marketGoods := [" + ", ".join(f'({quote(item["building"])}, {item["highest"]})' for item in r["marketGoods"]) + "]",
    "  loanOffices := [" + ", ".join(str(item["officeLevel"]) for item in r["loans"]) + "]",
    "  spells := spellIdentities.map Prod.snd", "  gods := godIdentities.map Prod.snd",
])
for field in ["dragonLevel", "santaLevel", "officeLevel", "gardenLevel", "ascensionMode"]:
    lines.append(f"  {field} := {r[field]}")
lines.extend(["", "end CookieClicker.FullGame.Pinned", ""])
expected = "\n".join(lines)
output = root / "CookieClicker/Inventory.lean"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if not output.exists() or output.read_text() != expected:
        sys.exit("Lean inventory is stale. Run python3 lean/generate_inventory.py")
    print("Lean inventory matches the pinned completion requirements.")
else:
    output.write_text(expected)
    print(f"Wrote {output.relative_to(repository)}")
