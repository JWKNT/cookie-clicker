import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { compileJavaScript } from '../model/javascript-ast.mjs';
import { loadGameSource } from '../model/game-source.mjs';

const source = loadGameSource();
const main = source.sources['main.js'];
const rows = [];
const definitions = [];
for (const name of ['Earn', 'Spend']) {
  const text = new RegExp('Game\\.' + name + '=(function\\(howmuch\\)\\s*\\{[^}]*\\})').exec(main)?.[1];
  assert(text, `Missing pinned Game.${name}`);
  const ast = compileJavaScript('(' + text + ');', { name: `Game.${name}` });
  const root = ast.nodes[ast.units[0].root];
  assert.equal(root.body.length, 1);
  const fn = ast.nodes[ast.nodes[root.body[0]].expression];
  assert.equal(fn.tag, 'function');
  assert.deepEqual(fn.parameters, ['howmuch']);
  assert.equal(fn.strict, false);
  const render = id => {
    const n = ast.nodes[id];
    if (n.tag === 'identifier') return `(.identifier ${JSON.stringify(n.name)})`;
    if (n.tag === 'member') return `(.member ${render(n.object)} ${render(n.property)} ${n.computed})`;
    if (n.tag === 'assignment' && ['add', 'subtract'].includes(n.operator))
      return `(.assignment .${n.operator} ${render(n.left)} ${render(n.right)})`;
    if (n.tag === 'expression') return `.expression ${render(n.expression)}`;
    throw new Error(`Unsupported counter source node ${n.tag}`);
  };
  const digest = createHash('sha256').update(text).digest('hex');
  definitions.push(`-- Game.${name} source SHA-256: ${digest}\ndef ${name.toLowerCase()}Body : Stmt := .block [\n  ${fn.body.map(render).join(',\n  ')}]\n`);
  rows.push({ name, nodes: ast.nodes.length, sourceSha256: digest });
}
const output = `import CookieClicker.JavaScriptSyntax

/- Generated by tools/generate-counter-source.mjs from the pinned game.
main.js SHA-256: ${source.hashes['main.js']}
The frontend and source-byte correspondence remain separate proof obligations.
These bodies retain the source compound-assignment order. -/
namespace CookieClicker.JavaScript.CounterSyntax

${definitions.join('\n')}
end CookieClicker.JavaScript.CounterSyntax
`;
const path = new URL('../lean/CookieClicker/JavaScriptCounterSyntax.lean', import.meta.url);
if (process.argv.includes('--check')) assert.equal(readFileSync(path, 'utf8'), output, 'Counter source is stale');
else writeFileSync(path, output);
console.log(JSON.stringify({ check: process.argv.includes('--check'), functions: rows }));
