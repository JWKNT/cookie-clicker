import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { compileJavaScript } from '../model/javascript-ast.mjs';

const source = readFileSync(new URL('../model/semantics/v8-timsort.js', import.meta.url), 'utf8');
const ast = compileJavaScript(source, { name: 'private-v8-timsort.js' });
const digest = createHash('sha256').update(source).digest('hex');
const output = `import CookieClicker.JavaScriptDecode

/- Generated by tools/generate-timsort-ast.mjs.
Source SHA-256: ${digest}
The typed decoder checks syntax structure; source correspondence is separate. -/
namespace CookieClicker.JavaScript.TimSortSyntax

private def artifact : String := ${JSON.stringify(JSON.stringify(ast))}

def function : Except String Expr := do
  let decoded ← decodeArtifact (← Lean.Json.parse artifact)
  let some unit := decoded.units[0]? | throw "Missing private TimSort unit"
  match unit.program.body with
  | [.expression expression] => pure expression
  | _ => throw "Private TimSort unit must contain one function expression"

end CookieClicker.JavaScript.TimSortSyntax
`;
const path = new URL('../lean/CookieClicker/JavaScriptTimSortSyntax.lean', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw new Error('TimSort AST is stale');
} else writeFileSync(path, output);
console.log(JSON.stringify({ nodes: ast.nodes.length, sourceSha256: digest, check: process.argv.includes('--check') }));
