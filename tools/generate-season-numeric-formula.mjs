import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const arg=n=>{const i=process.argv.indexOf(n);return i<0?null:process.argv[i+1];};
const root=resolve(arg('--root')||join(dirname(fileURLToPath(import.meta.url)),'..'));
const leanRoot=resolve(arg('--lean-root')||join(root,'lean'));
const reportPath=arg('--report')||join(root,'model/natural-season-source.json');
const report=JSON.parse(readFileSync(reportPath));
const {loadGameSource}=await import(pathToFileURL(join(root,'model/game-source.mjs')));
const source=loadGameSource();assert.equal(source.hashes['main.js'],report.mainSha256);
const require=createRequire(join(root,'source/cookie-monster-plus/package.json'));const acorn=require('acorn');
const hash=v=>createHash('sha256').update(v).digest('hex');
const expected=['century','goldenNumber','centuryCorrection','rawEpact','epact0','correctEpact','rawWeekday','easterWeekday','easterOffset','easterMonth','easterMonthDay'];
assert.deepEqual(report.extractedFormulas.map(r=>r.name),expected);
const names={Y:'y',C:'(century y)',N:'(goldenNumber y)',K:'(centuryCorrection y)',I:'(epact y)',J:'(easterWeekday y)',L:'(easterOffset y)',M:'(easterMonth y)'};
const render=(n,vars)=>{
 if(n.type==='Identifier'){assert(n.name in vars,n.name);return vars[n.name];}
 if(n.type==='Literal'){assert(Number.isSafeInteger(n.value)&&n.value>=0);return `(Number.ofNat ${n.value})`;}
 if(n.type==='BinaryExpression'){const op={'+':'add','-':'sub','*':'mul','/':'div'}[n.operator];assert(op);return `(Number.${op} ${render(n.left,vars)} ${render(n.right,vars)})`;}
 if(n.type==='CallExpression'){assert.equal(n.callee.type,'MemberExpression');assert.equal(n.callee.object.name,'Math');assert.equal(n.callee.property.name,'floor');assert.equal(n.arguments.length,1);return `(Number.floor ${render(n.arguments[0],vars)})`;}
 throw new Error(n.type);
};
const defs=[];
for(const row of report.extractedFormulas){
 assert.equal(hash(row.nativeText),row.sourceSha256);assert(source.sources['main.js'].includes(row.nativeText));
 const n=acorn.parseExpressionAt(row.nativeText,0,{ecmaVersion:5});assert.equal(n.end,row.nativeText.length);
 const vars={...names};if(row.name==='epact0')vars.I='(rawEpact y)';if(row.name==='easterWeekday')vars.J='(rawWeekday y)';
 if(row.name==='correctEpact'){vars.I='i';vars.N='n';}
 defs.push(`def ${row.name} ${row.name==='correctEpact'?'(i n : UInt64)':'(y : UInt64)'} : UInt64 :=\n  ${render(n,vars)}`);
 if(row.name==='correctEpact')defs.push('def epact (y : UInt64) : UInt64 := correctEpact (epact0 y) (goldenNumber y)');
}
const output=`import CookieClicker.JavaScriptNumber

/- Generated by tools/generate-season-numeric-formula.mjs from the checked
natural-season source expression report. main.js SHA-256: ${report.mainSha256}
Native operation order and repeated subexpressions are retained. These pure
Number expressions do not replace the source interpreter or its heap calls. -/
namespace CookieClicker.JavaScript.NaturalSeasonNumber

${defs.join('\n\n')}

end CookieClicker.JavaScript.NaturalSeasonNumber
`;
const target=join(leanRoot,'CookieClicker/JavaScriptSeasonNumericFormula.lean');
if(process.argv.includes('--check'))assert.equal(readFileSync(target,'utf8'),output);else writeFileSync(target,output);
console.log(JSON.stringify({check:process.argv.includes('--check'),sourceExpressions:expected.length,sourceReportSha256:hash(readFileSync(reportPath)),outputSha256:hash(output)}));
