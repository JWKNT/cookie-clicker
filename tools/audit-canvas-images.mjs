/** Audit exact pinned PNG bytes for animation and orientation chunks. */
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import {loadGameSource} from '../model/game-source.mjs';
const root=new URL('../',import.meta.url),manifest=JSON.parse(readFileSync(new URL('model/game-assets.json',root)));
const game=loadGameSource(),assets=[];
for(const asset of manifest.assets.filter(a=>a.mime==='image/png')){
 const bytes=readFileSync(join(game.directory,asset.path));
 assert.equal(createHash('sha256').update(bytes).digest('hex'),asset.sha256);
 assert.equal(bytes.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
 let offset=8;const chunks=[];
 while(offset<bytes.length){assert.ok(offset+12<=bytes.length);const length=bytes.readUInt32BE(offset),kind=bytes.toString('ascii',offset+4,offset+8);assert.ok(offset+12+length<=bytes.length);chunks.push(kind);offset+=12+length;if(kind==='IEND')break;}
 assert.equal(offset,bytes.length);assert.equal(chunks[0],'IHDR');assert.equal(chunks.at(-1),'IEND');
 const width=bytes.readUInt32BE(16),height=bytes.readUInt32BE(20);
 assert.equal(width,asset.native.naturalWidth);assert.equal(height,asset.native.naturalHeight);
 const animated=chunks.some(c=>['acTL','fcTL','fdAT'].includes(c)),exif=chunks.includes('eXIf');
 assets.push({path:asset.path,sha256:asset.sha256,width,height,chunks,animated,exif,admitted:!animated&&!exif});
}
const jpegAssets=[];
for(const asset of manifest.assets.filter(a=>a.mime==='image/jpeg')){
 const bytes=readFileSync(join(game.directory,asset.path));
 assert.equal(createHash('sha256').update(bytes).digest('hex'),asset.sha256);
 assert.equal(bytes.readUInt16BE(0),0xffd8);
 let offset=2,width=null,height=null,scanning=false;const markers=[],orientations=[];
 while(offset<bytes.length){
  if(scanning){while(offset<bytes.length){if(bytes[offset++]!==255)continue;while(bytes[offset]===255)offset++;const marker=bytes[offset];if(marker===0||(marker>=0xd0&&marker<=0xd7)){offset++;continue;}offset--;break;}scanning=false;}
  assert.equal(bytes[offset++],255);while(bytes[offset]===255)offset++;
  const marker=bytes[offset++];markers.push(marker);if(marker===0xd9)break;
  assert.ok(offset+2<=bytes.length);const length=bytes.readUInt16BE(offset);assert.ok(length>=2&&offset+length<=bytes.length);
  if([0xc0,0xc1,0xc2].includes(marker)){height=bytes.readUInt16BE(offset+3);width=bytes.readUInt16BE(offset+5);}
  if(marker===0xe1&&bytes.subarray(offset+2,offset+8).toString('ascii')==='Exif\0\0'){
   const start=offset+8,end=offset+length,little=bytes.toString('ascii',start,start+2)==='II';
   assert.ok(little||bytes.toString('ascii',start,start+2)==='MM');
   const u16=p=>{assert.ok(p>=start&&p+2<=end);return little?bytes.readUInt16LE(p):bytes.readUInt16BE(p);};
   const u32=p=>{assert.ok(p>=start&&p+4<=end);return little?bytes.readUInt32LE(p):bytes.readUInt32BE(p);};
   assert.equal(u16(start+2),42);const ifd=start+u32(start+4),count=u16(ifd);
   for(let i=0;i<count;i++){const entry=ifd+2+i*12;assert.ok(entry+12<=end);if(u16(entry)===0x112){assert.equal(u16(entry+2),3);assert.equal(u32(entry+4),1);orientations.push(u16(entry+8));}}
  }
  offset+=length;if(marker===0xda)scanning=true;
 }
 assert.equal(markers.at(-1),0xd9);const trailingByteCount=bytes.length-offset;
 assert.equal(width,asset.native.naturalWidth);assert.equal(height,asset.native.naturalHeight);
 jpegAssets.push({path:asset.path,sha256:asset.sha256,width,height,markers,orientations,trailingByteCount,admitted:orientations.every(value=>value===1)});
}
const report=JSON.stringify({sourceHashes:game.hashes,pngAssets:assets,jpegAssets,byteParserVerified:false,decoderRefinementVerified:false,originCleanRefinementVerified:false},null,2)+'\n';
const lean=`/-! Generated by tools/audit-canvas-images.mjs from exact pinned image bytes.
PNG admission excludes APNG control/frame chunks and eXIf orientation metadata.
JPEG admission requires absent or identity IFD0 orientation; SOF dimensions
match the captured native natural dimensions. This byte audit is not a verified
decoder or an origin-clean theorem. -/
namespace CookieClicker.JavaScript.BrowserCanvasImageAssets

def staticPngHashes : List String := [\n${assets.filter(a=>a.admitted).map(a=>'  '+JSON.stringify(a.sha256)).join(',\n')}\n]\n
def ordinaryJpegHashes : List String := [\n${jpegAssets.filter(a=>a.admitted).map(a=>'  '+JSON.stringify(a.sha256)).join(',\n')}\n]\n
end CookieClicker.JavaScript.BrowserCanvasImageAssets\n`;
for(const [path,content]of [[new URL('model/canvas-images-witness.json',root),report],[new URL('lean/CookieClicker/JavaScriptBrowserCanvasImageAssets.lean',root),lean]]){
 if(process.argv.includes('--check'))assert.equal(readFileSync(path,'utf8'),content,'Stale canvas image source audit');else writeFileSync(path,content);
}
console.log(JSON.stringify({pngAssets:assets.length,admittedPng:assets.filter(a=>a.admitted).length,animated:assets.filter(a=>a.animated).length,exif:assets.filter(a=>a.exif).length,jpegAssets:jpegAssets.length,admittedJpeg:jpegAssets.filter(a=>a.admitted).length,jpegOrientations:[...new Set(jpegAssets.flatMap(a=>a.orientations))]}));
