import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { compileJavaScript } from '../model/javascript-ast.mjs';
import { loadGameSource } from '../model/game-source.mjs';

const require = createRequire(new URL('../source/cookie-monster-plus/package.json', import.meta.url));
const acorn = require('acorn'), source = loadGameSource(), text = source.sources['main.js'];
const fn = acorn.parse(text, { ecmaVersion: 5 }).body.find(node => node.type === 'FunctionDeclaration' && node.id.name === 'choose');
assert(fn); assert.deepEqual(fn.params.map(param => param.name), ['arr']);
const nativeText = text.slice(fn.start, fn.end);
const sourceSha256 = createHash('sha256').update(nativeText).digest('hex');
const ast = compileJavaScript(nativeText, { name: 'native-choose' });
const declaration = ast.nodes[ast.nodes[ast.units[0].root].body[0]];
const render = id => {
  const node = ast.nodes[id];
  if (node.tag === 'identifier') return `(.identifier ${JSON.stringify(node.name)})`;
  if (node.tag === 'member') return `(.member ${render(node.object)} ${render(node.property)} ${node.computed})`;
  if (node.tag === 'call') return `(.call ${render(node.callee)} [${node.arguments.map(render).join(', ')}])`;
  if (node.tag === 'binary') return `(.binary .${node.operator} ${render(node.left)} ${render(node.right)})`;
  if (node.tag === 'return') return `(.return (some ${render(node.value)}))`;
  throw new Error(`Unreviewed native choose node: ${node.tag}`);
};
const output = `import CookieClicker.JavaScriptSyntax

/- Generated by tools/generate-choice-source.mjs from the pinned source.
main.js SHA-256: ${source.hashes['main.js']}
choose source SHA-256: ${sourceSha256}
The native body retains every property read, call and arithmetic operation.
Source-byte/parser correspondence remains a separate proof obligation. -/
namespace CookieClicker.JavaScript.ChoiceSyntax

def body : Stmt := .block [${declaration.body.map(render).join(', ')}]

end CookieClicker.JavaScript.ChoiceSyntax
`;
const path = new URL('../lean/CookieClicker/JavaScriptChoiceSyntax.lean', import.meta.url);
if (process.argv.includes('--check')) assert.equal(readFileSync(path, 'utf8'), output);
else writeFileSync(path, output);
console.log(JSON.stringify({ check: process.argv.includes('--check'), sourceSha256, nodes: ast.nodes.length }));
