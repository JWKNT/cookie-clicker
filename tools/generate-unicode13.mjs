import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const sources = {
  'UnicodeData.txt':'bdbffbbfc8ad4d3a6d01b5891510458f3d36f7170422af4ea2bed3211a73e8bb',
  'SpecialCasing.txt':'6424312f1dc39b22e0ff9c0ffb13dfad424d9b03e6a6dc6bca941f6bf5ef1ffd',
  'DerivedCoreProperties.txt':'a5d45f59b39deaab3c72ce8c1a2e212a5e086dff11b1f9d5bb0e352642e82248',
  'CaseFolding.txt':'99d231d7c91688bbe8ca8ccebcc2f46b5b222f844babe4827295bae11e2abe5f',
};
const data={};
for(const [file,hash] of Object.entries(sources)){
  const bytes=readFileSync(new URL(`../model/unicode13/${file}`,import.meta.url));
  if(createHash('sha256').update(bytes).digest('hex')!==hash)throw Error(`Unicode source hash mismatch: ${file}`);
  data[file]=bytes.toString('utf8');
}
const hex = text => Number.parseInt(text,16);
const sequence = text => text.trim()?text.trim().split(/\s+/).map(hex):[];
const rows = text => text.split(/\r?\n/).map(line=>line.split('#')[0].trim()).filter(Boolean).map(line=>line.split(';').map(s=>s.trim()));
const merge = ranges => {
  const result=[];
  for(const [start,end] of ranges.sort((a,b)=>a[0]-b[0])){
    const last=result.at(-1);
    if(last&&start<=last[1]+1)last[1]=Math.max(last[1],end);else result.push([start,end]);
  }
  return result;
};
const letters=[];const lower=new Map();const upper=new Map();let first=null;
for(const row of rows(data['UnicodeData.txt'])){
  const cp=hex(row[0]);
  if(row[1].endsWith(', First>')){first={cp,category:row[2]};continue;}
  if(row[1].endsWith(', Last>')){
    if(!first||first.category!==row[2])throw Error('Mismatched Unicode range');
    if(row[2].startsWith('L'))letters.push([first.cp,cp]);first=null;continue;
  }
  if(row[2].startsWith('L'))letters.push([cp,cp]);
  if(row[12])upper.set(cp,[hex(row[12])]);
  if(row[13])lower.set(cp,[hex(row[13])]);
}
if(first)throw Error('Unclosed Unicode range');
let finalSigma=false;
for(const [code,l,,u,condition] of rows(data['SpecialCasing.txt'])){
  if(!condition){lower.set(hex(code),sequence(l));upper.set(hex(code),sequence(u));}
  else if(condition==='Final_Sigma'){
    if(code!=='03A3'||l!=='03C2')throw Error('Unexpected contextual mapping');finalSigma=true;
  }else if(!/^(lt|tr|az)( |$)/.test(condition))throw Error(`Unsupported default casing condition: ${condition}`);
}
if(!finalSigma)throw Error('Missing final sigma rule');
const properties={Cased:[],Case_Ignorable:[]};
for(const [range,property] of rows(data['DerivedCoreProperties.txt']))if(properties[property]){
  const [start,end=start]=range.split('..').map(hex);properties[property].push([start,end]);
}
const fold=new Map();
for(const [code,status,mapping] of rows(data['CaseFolding.txt']))if(status==='C'||status==='S'){
  const mapped=sequence(mapping);if(mapped.length!==1)throw Error('Simple fold is not singleton');fold.set(hex(code),mapped[0]);
}
const normalized=map=>[...map].filter(([cp,mapping])=>!(mapping.length===1&&mapping[0]===cp)).sort((a,b)=>a[0]-b[0]);
const ranges=(name,value)=>`def ${name} : Array (Nat × Nat) := #[\n${merge(value).map(([a,b])=>`  (${a}, ${b})`).join(',\n')}\n]\n`;
const mappings=(name,value)=>{
  const entries=normalized(value);const chunks=[];
  for(let start=0;start<entries.length;start+=256)chunks.push(entries.slice(start,start+256));
  return chunks.map((chunk,i)=>`private def ${name}${i} : Array (Nat × List Nat) := #[\n${chunk.map(([cp,m])=>`  (${cp}, [${m.join(', ')}])`).join(',\n')}\n]\n`).join('\n')
    +`\ndef ${name} : Array (Nat × List Nat) := ${chunks.map((_,i)=>`${name}${i}`).join(' ++ ')}\n`;
};
const content=`import Std

/-! Generated by tools/generate-unicode13.mjs from official Unicode 13.0.0 data.
Source bytes are hash-checked by the generator. Retained license:
model/unicode13/LICENSE.txt. The table generator is not a proved source parser.
${Object.entries(sources).map(([file,hash])=>`${file}: ${hash}`).join('\n')}
-/
namespace CookieClicker.JavaScript.Unicode.Data

set_option maxRecDepth 10000
set_option maxHeartbeats 4000000

${ranges('letterRanges',letters)}
${ranges('casedRanges',properties.Cased)}
${ranges('caseIgnorableRanges',properties.Case_Ignorable)}
${mappings('lowerMappings',lower)}
${mappings('upperMappings',upper)}
${mappings('foldMappings',new Map([...fold].map(([cp,to])=>[cp,[to]])))}
end CookieClicker.JavaScript.Unicode.Data
`;
const output=fileURLToPath(new URL('../lean/CookieClicker/JavaScriptUnicodeData.lean',import.meta.url));
if(process.argv.includes('--check')){
  if(readFileSync(output,'utf8')!==content)throw Error('Unicode Lean tables are stale');
}else writeFileSync(output,content);
console.log(JSON.stringify({unicode:'13.0.0',letterRanges:merge(letters).length,
  lowerMappings:normalized(lower).length,upperMappings:normalized(upper).length,simpleFolds:fold.size,sourceHashesVerified:true}));
